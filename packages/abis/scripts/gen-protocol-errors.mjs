/**
 * Regenerates `src/protocolErrors.ts` from the compiled Foundry artifacts.
 *
 * Run after any `lib/tbv-contracts` bump:
 *   forge build && \
 *   forge build lib/tbv-contracts/src/applications/aave/resolvers/borrow-delegation/BorrowDelegationPositionAccount.sol && \
 *   pnpm --filter @repo/abis gen:errors && pnpm biome format --write packages/abis/src
 *
 * The second `forge build` is needed because nothing in this repo imports the borrow-delegation
 * position account, so a plain build never emits its artifact — but a liquidation against a
 * borrower using that resolver can still revert from inside it.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { toFunctionSelector } from "viem";

const PKG = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(PKG, "..", "..", "out");

/**
 * Contracts whose errors can reach a bot. The first five are called directly; the rest are what
 * those call into, and a revert raised there propagates unchanged to the caller — which is the
 * whole reason this union exists.
 */
const CONTRACTS = [
  "BTCVaultSwap",
  "AaveAdapter",
  "AaveAdapterLens",
  "LiquidationRouter",
  "ArbitrageRouter",
  "Spoke",
  "BTCVaultRegistry",
  "ApplicationRegistry",
  "AaveAdapterPositionProxy",
  "BorrowDelegationPositionAccount",
];

function findArtifact(contract) {
  const stack = [OUT];
  while (stack.length > 0) {
    const dir = stack.pop();
    for (const entry of readdirSync(dir)) {
      const path = join(dir, entry);
      if (statSync(path).isDirectory()) stack.push(path);
      else if (entry === `${contract}.json`) return path;
    }
  }
  return undefined;
}

const paramType = (p) =>
  p.type.startsWith("tuple")
    ? `(${(p.components ?? []).map(paramType).join(",")})${p.type.slice("tuple".length)}`
    : p.type;
const signature = (e) => `${e.name}(${(e.inputs ?? []).map(paramType).join(",")})`;

const bySelector = new Map();
for (const contract of CONTRACTS) {
  const path = findArtifact(contract);
  if (path === undefined) {
    console.error(`no artifact for ${contract} — run the forge builds in this file's header first`);
    process.exit(1);
  }
  for (const entry of JSON.parse(readFileSync(path, "utf8")).abi) {
    if (entry.type !== "error") continue;
    const sig = signature(entry);
    const selector = toFunctionSelector(sig);
    const seen = bySelector.get(selector);
    if (seen === undefined) {
      bySelector.set(selector, { sig, entry });
    } else if (seen.sig !== sig) {
      // Merging into one list is only sound while selectors are unique across these contracts.
      console.error(`selector collision ${selector}: ${seen.sig} vs ${sig}`);
      process.exit(1);
    }
  }
}

/** Emits a param, recursing into tuple components — dropping them silently breaks decoding. */
const renderParam = (p) => {
  const base = `{ name: ${JSON.stringify(p.name)}, type: ${JSON.stringify(p.type)}`;
  if (!p.type.startsWith("tuple")) return `${base} }`;
  return `${base}, components: [${(p.components ?? []).map(renderParam).join(", ")}] }`;
};
const renderEntry = ({ entry }) =>
  `  { type: "error", name: ${JSON.stringify(entry.name)}, inputs: [${(entry.inputs ?? []).map(renderParam).join(", ")}] },`;

const entries = [...bySelector.values()].sort((a, b) => a.sig.localeCompare(b.sig));

const header = `// GENERATED by scripts/gen-protocol-errors.mjs — do not edit by hand.
/**
 * Every custom error the contracts in the bots' call graph can revert with, as one flat ABI
 * fragment list.
 *
 * A revert is decoded against the ABI passed to the call that made it, and viem can only name an
 * error whose selector it finds there. That matters here because the contracts the bots call are
 * thin: \`swapWbtcForVault\` reverts from inside \`ApplicationRegistry\` or \`BTCVaultRegistry\` at
 * least as often as it does with one of \`BTCVaultSwap\`'s own errors. \`UnauthorizedVaultKeeper()\`
 * — what an unregistered keeper hits on its first acquisition — is declared in
 * \`ApplicationRegistry\`, so a per-contract ABI misses it and viem surfaces a bare \`0xc2732b47\`
 * that nothing downstream can classify.
 *
 * Hence a union rather than a per-contract list: it is spread into every ABI the bots call through,
 * so a selector decodes no matter which contract in the call graph raised it. Selectors are
 * globally unique across these contracts, which is what makes merging them into one list safe.
 *
 * \`protocolErrors.test.ts\` pins every entry back to the artifacts and re-checks that uniqueness,
 * so a contracts bump that renames or re-types an error fails there rather than degrading into an
 * undecodable selector at runtime.
 */
export const protocolErrorsAbi = [
`;

const footer = `] as const;

/** Every error name \`protocolErrorsAbi\` can decode, as a union. */
export type ProtocolErrorName = (typeof protocolErrorsAbi)[number]["name"];
`;

const body = entries.map(renderEntry).join("\n");
writeFileSync(join(PKG, "src", "protocolErrors.ts"), `${header}${body}\n${footer}`);
console.log(`${entries.length} unique errors -> src/protocolErrors.ts`);
